function Get-TaskBranchType {
    param(
        [string]$PhaseCode,
        [string]$Mode,
        [string]$Title
    )

    if ($Title -match '(?i)bug|fix|finding|lỗi') {
        return 'fix'
    }

    if ($Title -match '(?i)test|kiểm thử|suite|benchmark|measure|verification|verify phase|audit|rehearsal|fault|adversarial|security scan') {
        return 'test'
    }

    if ($Title -match '(?i)doc|spec|decision|roadmap|scope|matrix|freeze|git|release note|changelog|task template|threat model|chuẩn hóa|chốt ') {
        return 'docs'
    }

    if ($Title -match '(?i)solution|project reference|ci |configuration|config |analyzer|installer|verified update|update integrity|sbom|dependency|package|tooling') {
        return 'chore'
    }

    if ($Mode -eq 'PLAN') {
        return 'docs'
    }

    if ($Mode -eq 'SECURITY_REVIEW') {
        return 'test'
    }

    if ($PhaseCode -eq 'P00') {
        return 'chore'
    }

    return 'feat'
}

function ConvertTo-BranchSlug {
    param([string]$Text)

    $source = $Text.Replace('Đ', 'D').Replace('đ', 'd')
    $normalized = $source.Normalize([System.Text.NormalizationForm]::FormD)
    $builder = [System.Text.StringBuilder]::new()

    foreach ($character in $normalized.ToCharArray()) {
        $category = [System.Globalization.CharUnicodeInfo]::GetUnicodeCategory($character)
        if ($category -ne [System.Globalization.UnicodeCategory]::NonSpacingMark) {
            [void]$builder.Append($character)
        }
    }

    $ascii = $builder.ToString().Normalize([System.Text.NormalizationForm]::FormC).ToLowerInvariant()
    $slug = ([regex]::Replace($ascii, '[^a-z0-9]+', '-')).Trim('-')
    if ([string]::IsNullOrWhiteSpace($slug)) {
        $slug = 'task'
    }

    if ($slug.Length -gt 48) {
        $slug = $slug.Substring(0, 48).TrimEnd('-')
        $lastSeparator = $slug.LastIndexOf('-')
        if ($lastSeparator -ge 24) {
            $slug = $slug.Substring(0, $lastSeparator)
        }
    }

    return $slug
}

