function Assert-PathWithinRepository {
    param([string]$Path)

    $resolved = [System.IO.Path]::GetFullPath($Path)
    $prefix = $repositoryRootPath.TrimEnd(
        [System.IO.Path]::DirectorySeparatorChar,
        [System.IO.Path]::AltDirectorySeparatorChar
    ) + [System.IO.Path]::DirectorySeparatorChar

    if (-not $resolved.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to write outside repository: $resolved"
    }
}

function Assert-GeneratedFileWriteAllowed {
    param(
        [string]$Path,
        [string]$Label
    )

    Assert-PathWithinRepository -Path $Path
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return
    }

    if (-not $Force) {
        throw "$Label already exists: $Path. Use -Force only after reviewing source and generated-file changes."
    }

    $firstLine = Get-Content -LiteralPath $Path -Encoding utf8 -TotalCount 1
    if ($firstLine -ne $generatedMarker -and -not $AdoptExisting) {
        throw "Refusing to overwrite unmanaged $Label`: $Path. Use -AdoptExisting only after confirming it is safe to replace."
    }
}

