function Get-LifecycleSummary {
    param([string]$Text)

    $mappings = [ordered]@{
        '(?i)account' = @('UserAccount', 'AssistantProfile')
        '(?i)device|pairing|rekey' = @('DeviceNode', 'DeviceSession')
        '(?i)voice|wake' = @('VoiceWakeProfile')
        '(?i)interaction|clarification|context' = @('InteractionSession', 'ClarificationRequest')
        '(?i)action plan|plan hash' = @('ActionPlan')
        '(?i)action engine|actiontask|action task|execution' = @('ActionPlan', 'ActionTask')
        '(?i)permission' = @('PermissionGrant')
        '(?i)confirmation' = @('ConfirmationRequest')
        '(?i)memory sync|tombstone|conflict' = @('MemoryRecord', 'MemorySyncJob')
        '(?i)memory' = @('MemoryRecord')
        '(?i)routine' = @('RoutineDefinition', 'RoutineRun')
        '(?i)skill|plugin' = @('SkillPackage')
        '(?i)terminal workflow|terminal runner' = @('TerminalWorkflowDefinition', 'WorkerProcess', 'ActionTask')
        '(?i)worker|process' = @('WorkerProcess')
        '(?i)integration connection|integration authorize|integration capability' = @('IntegrationConnection')
        '(?i)credential|secret|vault' = @('CredentialSecret')
        '(?i)message|recipient|delivery' = @('OutboundMessage')
        '(?i)home assistant|ha entity|ha read|ha low|ha policy' = @('IntegrationConnection', 'HomeAssistantEntityBinding')
        '(?i)provider|routing' = @('AiProviderConfiguration')
        '(?i)local model' = @('LocalModelRuntime')
        '(?i)browser|tab|ui target|extension' = @('UiTargetSnapshot')
        '(?i)audit' = @('AuditRecord')
        '(?i)safe mode|security incident|threat' = @('AssistantProfile', 'SecurityIncident')
    }

    $entities = [System.Collections.Generic.List[string]]::new()
    foreach ($entry in $mappings.GetEnumerator()) {
        if ($Text -match $entry.Key) {
            foreach ($entity in $entry.Value) {
                if (-not $entities.Contains($entity)) {
                    $entities.Add($entity)
                }
            }
        }
    }

    if ($entities.Count -eq 0) {
        return 'Không thay đổi lifecycle trực tiếp. Nếu task phát sinh transition mới, phải cập nhật lifecycle/spec trước khi implement.'
    }

    return ($entities | ForEach-Object { "``$_``" }) -join ', '
}

function Get-TestPlan {
    param(
        [string]$Mode,
        [string]$Risk,
        [string]$Title
    )

    if ($Mode -eq 'PLAN') {
        return @(
            '- Review: kiểm tra decision/spec/traceability và link nội bộ.',
            '- Validation: chạy validator tài liệu hoặc cấu hình áp dụng.',
            '- Manual: xác nhận output đủ để task phụ thuộc bắt đầu mà không suy đoán.'
        )
    }

    if ($Mode -eq 'RELEASE') {
        return @(
            '- Automated: chạy gate hoặc suite được nêu trong acceptance.',
            '- Security: bắt buộc cho release evidence.',
            '- Manual: lưu artifact/report và kết quả rollback/recovery khi áp dụng.'
        )
    }

    $items = [System.Collections.Generic.List[string]]::new()
    $items.Add('- Unit: kiểm tra outcome, guard và failure path của task.')

    if ($Title -match '(?i)adapter|persistence|outbox|worker|bridge|api|store|sync|send|home assistant|installer|update|integration') {
        $items.Add('- Integration/contract: kiểm tra boundary với fake, sandbox hoặc test service.')
    }

    if ($Title -match '(?i)solution|architecture|adapter|api|worker|extension|integration|persistence') {
        $items.Add('- Architecture: kiểm tra dependency/module boundary.')
    }

    if ($Risk -in @('High', 'Critical')) {
        $items.Add('- Security: kiểm tra deny path, input, permission, secret và abuse case áp dụng.')
    }

    if ($Title -match '(?i)ui|desktop|voice|wake|demo|benchmark|measure|journey|installer|release') {
        $items.Add('- Manual: lưu evidence quan sát được trên target/reference environment.')
    }

    return $items.ToArray()
}

